#!/usr/bin/env bash
# apply-lok.sh dark|light [wallpaper]
# Applies the fixed lok greyscale palette everywhere ii's wallpaper colours would go:
#   matugen templates (Quickshell colors.json, Hyprland, hyprlock, fuzzel, GTK 3/4),
#   terminal colours (material_colors.scss -> applycolor.sh), KDE colour scheme,
#   and Hyprland decoration overrides (~/.config/hypr/custom/lok.lua).
# Called by switchwall.sh when appearance.palette.type is "lok". 2026-11-12.
set -u
mode="${1:-dark}"
[[ "$mode" == "light" ]] || mode="dark"
wallpaper="${2:-}"
XDG_CONFIG_HOME="${XDG_CONFIG_HOME:-$HOME/.config}"
XDG_STATE_HOME="${XDG_STATE_HOME:-$HOME/.local/state}"
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
COLORS_DIR="$(dirname "$SCRIPT_DIR")"
GEN="$XDG_STATE_HOME/quickshell/user/generated"
OUT="$GEN/lok"
mkdir -p "$OUT"

scheme_name="$(python3 "$SCRIPT_DIR/lok_palette.py" --mode "$mode" --out "$OUT")" || exit 1

# matugen: render all ii templates from the fixed colours (keeps {{image}} = wallpaper)
if [[ -n "$wallpaper" ]]; then
    python3 - "$OUT/matugen.json" "$wallpaper" <<'EOF'
import json, sys
p, img = sys.argv[1], sys.argv[2]
d = json.load(open(p)); d["image"] = img; json.dump(d, open(p, "w"))
EOF
fi
matugen -c "$XDG_CONFIG_HOME/matugen/config.toml" json "$OUT/matugen.json" --mode "$mode" >/dev/null

# terminal colours
cp "$OUT/material_colors.scss" "$GEN/material_colors.scss"
"$COLORS_DIR/applycolor.sh"

# KDE / Qt apps
mkdir -p "$HOME/.local/share/color-schemes"
cp "$OUT/$scheme_name.colors" "$HOME/.local/share/color-schemes/"
if command -v plasma-apply-colorscheme >/dev/null; then
    # re-applying the scheme already in use is a no-op (edits would not land), so bounce via Breeze
    if [[ "$(kreadconfig6 --file kdeglobals --group General --key ColorScheme 2>/dev/null)" == "$scheme_name" ]]; then
        plasma-apply-colorscheme BreezeDark >/dev/null 2>&1 || true
    fi
    plasma-apply-colorscheme "$scheme_name" >/dev/null 2>&1 || true
fi
# Plasma window decoration: when the lok Aurorae themes are in use, follow the mode
# (generated by ~/.local/share/lok-plasma/make_lok_aurorae.py; Plasma-only, Hyprland ignores kwinrc)
if [[ -d "$HOME/.local/share/aurorae/themes/lok-$mode" ]] \
   && [[ "$(kreadconfig6 --file kwinrc --group org.kde.kdecoration2 --key theme 2>/dev/null)" == __aurorae__svg__lok-* ]]; then
    for g in org.kde.kdecoration2 org.kde.kdecoration3; do
        kwriteconfig6 --file kwinrc --group "$g" --key theme "__aurorae__svg__lok-$mode"
    done
    qdbus6 org.kde.KWin /KWin reconfigure >/dev/null 2>&1 || true
fi

# Hyprland decoration: square, 1 px grey borders, no shadow (loaded by custom/general.lua)
if [[ "$mode" == "dark" ]]; then active="8a8a8a"; inactive="2e2e2e"; else active="6e6e6e"; inactive="cfcfcf"; fi
cat > "$XDG_CONFIG_HOME/hypr/custom/lok.lua" <<EOF
-- Generated by quickshell ii scripts/colors/lok/apply-lok.sh ($mode). Do not edit:
-- rewritten on every lok colour apply, emptied when another palette is used.
hl.config({
    general = {
        border_size = 1,
        -- lok: no gaps; 1 px borders are the only separation
        gaps_in = 0,
        gaps_out = 0,
        col = {
            active_border = "rgba(${active}ff)",
            inactive_border = "rgba(${inactive}ff)",
        },
    },
    decoration = {
        rounding = 0,
        shadow = { enabled = false },
    },
})
EOF
if [[ -n "${HYPRLAND_INSTANCE_SIGNATURE:-}" ]]; then
    hyprctl reload >/dev/null 2>&1 || true
fi
echo "lok $mode applied ($scheme_name)"
